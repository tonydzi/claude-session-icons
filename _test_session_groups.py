#!/usr/bin/env python3
"""_test_session_groups.py -- регресс движка иконок (0 LLM, 0 сети, не читает диск приложения).

Красный контроль: каждый кейс падал на версии до 10.09.2026 (словесные теги) либо ловит
конкретную граблю (двойная иконка, потеря «Р+», чужой тег). Прогон: python _test_session_groups.py
updated: 2026-09-10
"""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import session_groups as sg

F = []


def eq(got, want, name):
    if got != want:
        F.append(name + ": получил " + repr(got) + ", ждали " + repr(want))


# 1. голое имя -> иконка впереди
eq(sg.retitle("Долги ZBOOKG8", "Инфра"), "⚙️ Долги ZBOOKG8", "голое имя")
# 2. словесный тег мигрирует в иконку, слово исчезает
eq(sg.retitle("[Инфра] Долги ZBOOKG8", "Инфра"), "⚙️ Долги ZBOOKG8", "миграция тега")
# 3. идемпотентность: вторая прогонка не плодит вторую иконку
eq(sg.retitle("⚙️ Долги ZBOOKG8", "Инфра"), "⚙️ Долги ZBOOKG8", "идемпотентность")
# 4. смена группы меняет иконку, а не добавляет
eq(sg.retitle("⚙️ Статья про рейз", "$$$"), "💰 Статья про рейз", "смена группы")
# 5. «Р+» (веха) переживает переименование
eq(sg.retitle("Р+Разбор сессии", "2мозг"), "🧠 Р+Разбор сессии", "веха Р+ жива")
# 6. мусорный префикс Антона сохраняется впереди
eq(sg.retitle("!!Переосмысление", "Инфра"), "!!⚙️ Переосмысление", "мусор впереди")
# 7. чужой тег не съедается
eq(sg.retitle("[GROWTH] Найм", "$$$"), "💰 [GROWTH] Найм", "чужой тег цел")
# 8. неопределённое -> вопросик, Антон разберёт сам
eq(sg.retitle("3D game", "?"), "❓ 3D game", "неопределённое")
# 9. распознавание метки в обе стороны
eq(sg.tag_of("⚙️ Долги")[1], "Инфра", "чтение иконки")
eq(sg.tag_of("[ДРы] Веер")[1], "ДРы", "чтение словесного тега")
eq(sg.tag_of("Просто имя")[1], "", "метки нет")
eq(sg.tag_of("[GROWTH] Найм")[1], "", "чужой тег не наш")
# 10. классификатор
eq(sg.guess("Пульт ZBook 10.09"), "Инфра", "пульт -> Инфра")
eq(sg.guess("DR-веер DR26-08-28"), "ДРы", "DR -> ДРы")
eq(sg.guess("3D game"), "?", "непонятное -> ?")
# 11. у каждой финальной группы есть иконка и она уникальна
eq(sorted(sg.ICON) == sorted(sg.FINAL + ["?"]), True, "иконка у каждой группы")
eq(len(set(sg.ICON.values())), len(sg.ICON), "иконки уникальны")

if F:
    print("FAIL " + str(len(F)))
    print("\n".join(" - " + x for x in F))
    sys.exit(1)
print("OK 17/17")
